using UnityEngine;
using SaveSystem;
using SaveSystem.Data;

public sealed class GameBootstrapper : MonoBehaviour
{
    private SaveSystem.SaveSystem _saveSystem;
    private GameData              _gameData;

    private void Awake()
    {
        // ----------------------------------------------------------------
        // 1. Создаём систему сохранений
        //    В редакторе удобнее смотреть файлы рядом с проектом,
        //    в сборке — в папке данных приложения.
        // ----------------------------------------------------------------
        string saveFolder = Application.isEditor
            ? Application.dataPath
            : Application.persistentDataPath;

        _saveSystem = new SaveSystem.SaveSystem(saveFolder);

        // ----------------------------------------------------------------
        // 2. Загружаем данные при старте
        // ----------------------------------------------------------------
        _gameData = _saveSystem.Load();

        // Если сохранения нет — _gameData будет свежим (new GameData())
        // Если есть — восстановим прогресс и состояние игрока
    }

    // ----------------------------------------------------------------
    // 3. Сохраняем, когда нужно
    //    Триггеры — на ваш выбор: чекпоинт, смерть, переход сцены, таймер
    // ----------------------------------------------------------------
    public void OnCheckpointReached()
    {
        // TODO: перед сохранением обновите _gameData актуальными данными:
        // _gameData.PlayerState.CurrentHp  = _player.Hp;
        // _gameData.PlayerState.CurrentSceneName = SceneManager.GetActiveScene().name;

        _saveSystem.Save(_gameData);
        Debug.Log("Игра сохранена.");
    }

    // ----------------------------------------------------------------
    // 4. Пример сброса прогресса (новая игра)
    // ----------------------------------------------------------------
    public void OnNewGame()
    {
        _saveSystem.DeleteSave();
        _gameData = new GameData();
        Debug.Log("Сохранение удалено, начинаем сначала.");
    }
}
